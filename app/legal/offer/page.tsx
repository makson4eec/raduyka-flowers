import { getDocumentVersion } from "@/lib/document-version";
import { getSiteContent } from "@/lib/content-store";
import EditableInfoDocument from "@/components/legal/EditableInfoDocument";
import Link from "next/link";
import { LEGAL_DOCUMENT_VERSION as ORIGINAL_LEGAL_DOCUMENT_VERSION, legalValue } from "@/lib/legal";

export async function generateMetadata() {
  const content = await getSiteContent();
  return { title: content.pages["offer"] ? content.pages["offer"].title + " — Радуйка" : "Публичная оферта — Радуйка" };
}

export const dynamic = "force-dynamic";

export default async function OfferPage() {
  const content = await getSiteContent();
  const LEGAL_DOCUMENT_VERSION = getDocumentVersion(content, "offer", ORIGINAL_LEGAL_DOCUMENT_VERSION);
  const sellerDetails = content.settings;
  const sellerDisplayName = () => [content.settings.legalStatus, content.settings.legalName].filter(Boolean).join(" ");
  if (content.pages["offer"]) return <EditableInfoDocument page={{ ...content.pages["offer"], version: getDocumentVersion(content, "offer", LEGAL_DOCUMENT_VERSION) }} settings={content.settings} />;

  return (
    <main className="legal-document">
      <p className="eyebrow">Дистанционная продажа</p>
      <h1>Публичная оферта</h1>
      <div className="legal-meta">Редакция от {LEGAL_DOCUMENT_VERSION}</div>
      <p>Настоящий документ содержит условия розничной купли-продажи товаров дистанционным способом на сайте {legalValue(sellerDetails.website)}. Продавец: {sellerDisplayName()}, ИНН {legalValue(sellerDetails.inn)}, ОГРН/ОГРНИП {legalValue(sellerDetails.ogrn)}.</p>

      <h2>1. Предмет договора</h2>
      <p>Продавец обязуется передать покупателю выбранные на сайте товары, а покупатель — принять и оплатить их на условиях оферты и подтверждённого заказа. Ассортимент, основные свойства, состав, количество, цена и доступные варианты указываются в карточке товара и в корзине.</p>
      <p>До заключения договора покупателю предоставляется обязательная информация о товаре в объёме, применимом к конкретному товару, включая основные потребительские свойства, цену и условия приобретения, сведения об изготовителе и месте изготовления, правила безопасного использования, сроки годности/службы и сведения о подтверждении соответствия, когда такие сведения установлены законом или для товара. Для растений также указываются видовое название и сведения об особенностях содержания.</p>

      <h2>2. Особенности живых цветов и авторских букетов</h2>
      <p>Живые цветы являются природным товаром, поэтому фактический оттенок, степень раскрытия бутонов, форма и расположение элементов могут незначительно отличаться от фотографии. Существенные изменения состава, влияющие на характер, стоимость или основные свойства выбранного товара, согласуются с покупателем до передачи товара.</p>
      <p>Если покупатель заказывает индивидуальную композицию по собственным параметрам, такой товар может иметь индивидуально-определённые свойства. Это учитывается при применении правил об отказе от товара надлежащего качества.</p>

      <h2>3. Оформление и заключение договора</h2>
      <p>Покупатель выбирает товары, способ получения и передаёт сведения, необходимые для исполнения заказа. После отправки формы сайт присваивает заказу уникальный номер и показывает подтверждение. Условия конкретного заказа включают выбранные товары, их количество, предварительную стоимость, способ получения и сведения, подтверждённые продавцом.</p>
      <p>Если для заказа требуется отдельное согласование фактического наличия цветов, замены элементов или тарифа доставки, продавец сообщает результат до оплаты. Стоимость доставки, не включённая в предварительную сумму сайта, доводится до покупателя до оплаты и становится частью согласованных условий заказа.</p>

      <h2>4. Цена и оплата</h2>
      <p>Цены указываются в рублях Российской Федерации. Итоговая стоимость товаров рассчитывается в корзине. Доставка может рассчитываться отдельно по адресу. Оплата производится способом, предложенным продавцом после подтверждения заказа. При расчёте продавец обеспечивает применение контрольно-кассовой техники и направление кассового чека в случаях и порядке, установленных законом.</p>

      <h2>5. Доставка и самовывоз</h2>
      <p>Условия доставки и самовывоза опубликованы на странице <Link href="/legal/payment-delivery">«Оплата и доставка»</Link>. Покупатель обязан предоставить корректный адрес и контактные данные. При доставке другому человеку покупатель предоставляет только данные, необходимые для передачи заказа.</p>
      <p>Если доставка состоялась в согласованный срок, но передать заказ невозможно по обстоятельствам на стороне покупателя или получателя, новый срок и возможные дополнительные расходы согласуются отдельно в пределах, допускаемых законом.</p>

      <h2>6. Качество, отказ от товара и претензии</h2>
      <p>Права покупателя при обнаружении недостатков определяются Законом РФ «О защите прав потребителей». Условия отказа от товара надлежащего качества при дистанционной продаже применяются с учётом статьи 26.1 указанного Закона, характера конкретного товара, правовой позиции Конституционного Суда РФ от 17 февраля 2026 года № 7-П и наличия у товара индивидуально-определённых свойств.</p>
      <p>Продавец не устанавливает условия, ограничивающие права потребителя по сравнению с законом. Подробный порядок обращения приведён на странице <Link href="/legal/returns-claims">«Возврат и претензии»</Link>.</p>

      <h2>7. Бонусная программа</h2>
      <p>При использовании бонусов к заказу применяются опубликованные <Link href="/legal/bonus-program">Правила бонусной программы</Link>. Бонусы не являются денежными средствами и уменьшают цену только в пределах правил программы.</p>

      <h2>8. Персональные данные</h2>
      <p>Обработка персональных данных осуществляется в соответствии с <Link href="/legal/privacy">Политикой обработки персональных данных</Link>. Когда обработка основана на согласии, оно запрашивается отдельно от принятия этой оферты.</p>

      <h2>9. Контакты и претензии</h2>
      <p>Информация о продавце, адресах и способах направления претензий постоянно размещена на странице <Link href="/legal/seller">«Сведения о продавце»</Link>.</p>

      <h2>10. Заключительные положения</h2>
      <p>К отношениям сторон применяется законодательство Российской Федерации. Если отдельное условие оферты противоречит обязательной норме закона, применяется норма закона, а остальные положения продолжают действовать.</p>
      <Link className="legal-back" href="/">← Вернуться в магазин</Link>
    </main>
  );
}
