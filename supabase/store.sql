-- Persistent catalog and orders for Vercel/Supabase deployment.
-- Safe to run more than once.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  subtitle text not null default '',
  care text not null default '',
  price integer not null check (price > 0),
  old_price integer,
  image text not null,
  tag text,
  stock text not null check (stock in ('today', 'few', 'soon')),
  size text not null,
  palette text not null check (palette in ('pink', 'white', 'bright', 'green')),
  kind text not null check (kind in ('catalog', 'flower', 'builder')),
  visible boolean not null default true,
  featured boolean not null default false,
  sort_order integer not null default 0,
  variants jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Existing projects: add flower-specific fields and expand product kinds safely.
alter table public.products
  add column if not exists care text not null default '';

alter table public.products
  add column if not exists variants jsonb not null default '[]'::jsonb;

alter table public.products
  drop constraint if exists products_kind_check;

alter table public.products
  add constraint products_kind_check
  check (kind in ('catalog', 'flower', 'builder'));

create table if not exists public.orders (
  id uuid primary key,
  order_number text not null unique,
  status text not null check (status in ('new','confirmed','assembling','ready','delivery','completed','cancelled')),
  payment_status text not null check (payment_status in ('pending','invoice_sent','paid','refunded')),
  delivery_method text not null check (delivery_method in ('delivery','pickup')),
  delivery_fee integer,
  card_added boolean not null default false,
  card_fee integer not null default 0,
  subtotal integer not null,
  discount integer not null default 0,
  total integer not null,
  recipient_type text check (recipient_type in ('self','other')),
  recipient_name text not null,
  recipient_phone text not null,
  customer_name text not null,
  customer_phone text not null,
  customer_user_id uuid references auth.users(id) on delete set null,
  bonus_spent integer not null default 0,
  bonus_earned integer not null default 0,
  address text not null default '',
  delivery_date text not null default '',
  delivery_time text not null default '',
  card_text text not null default '',
  admin_note text not null default '',
  items jsonb not null,
  idempotency_key_hash text unique,
  idempotency_fingerprint_hash text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_sort_idx on public.products(sort_order, id);
create index if not exists orders_created_idx on public.orders(created_at desc);
create index if not exists orders_customer_user_idx on public.orders(customer_user_id, created_at desc);

alter table public.products enable row level security;
alter table public.orders enable row level security;

grant all on table public.products to service_role;
grant all on table public.orders to service_role;
grant usage, select on sequence public.products_id_seq to service_role;
